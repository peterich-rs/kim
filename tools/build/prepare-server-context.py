#!/usr/bin/env python3
"""Project the server dependency closure into an independent Cargo workspace.

No client/agent skeletons or Codex checkout are needed. server.Cargo.lock is a
reviewed projection of the root lock. Refreshing it rejects new versions/sources.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SERVER_LOCK = ROOT / "tools/build/server.Cargo.lock"
ALLOWED_GROUPS = ("crates/shared/", "crates/server/", "services/")
ALLOWED_HELPERS = {"examples/kimbench", "examples/pkt-client", "tools/kim-server-migrate"}
CONFIGS = ("chat.toml", "gateway.toml", "royal.toml", "router.toml", "tgateway.toml")


def dependency_tables(manifest: dict):
    for scope in [manifest, *manifest.get("target", {}).values()]:
        for section in ("dependencies", "build-dependencies", "dev-dependencies"):
            yield scope.get(section, {})


def local_closure(workspace: dict, seeds: list[str]) -> tuple[dict[str, dict], set[str]]:
    """Read only server-reachable manifests, including test/build/target edges."""
    found: dict[str, dict] = {}
    inherited: set[str] = set()
    pending = list(seeds)
    while pending:
        member = pending.pop()
        if member in found:
            continue
        if not member.startswith(ALLOWED_GROUPS) and member not in ALLOWED_HELPERS:
            raise ValueError(f"server dependency reaches forbidden local package: {member}")
        manifest_path = ROOT / member / "Cargo.toml"
        manifest = tomllib.loads(manifest_path.read_text())
        found[member] = manifest
        for dependencies in dependency_tables(manifest):
            for name, raw in dependencies.items():
                if not isinstance(raw, dict):
                    continue
                if raw.get("workspace"):
                    inherited.add(name)
                    spec, base = workspace["dependencies"][name], ROOT
                else:
                    spec, base = raw, manifest_path.parent
                if isinstance(spec, dict) and "path" in spec:
                    path = (base / spec["path"]).resolve().relative_to(ROOT)
                    pending.append(path.as_posix())
    return found, inherited


def toml_value(value) -> str:
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} = {toml_value(v)}" for k, v in value.items()) + " }"
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, (str, bool, int, float)):
        return json.dumps(value, ensure_ascii=False)
    raise ValueError(f"unsupported manifest value: {value!r}")


def table(name: str, values: dict) -> str:
    return f"[{name}]\n" + "".join(f"{json.dumps(k)} = {toml_value(v)}\n" for k, v in values.items()) + "\n"


def projected_manifest(root: dict, members: dict[str, dict], inherited: set[str], seeds: list[str]) -> str:
    workspace = root["workspace"]
    names = {m["package"]["name"] for m in members.values()}
    output = "# Generated by tools/build/prepare-server-context.py; do not edit.\n\n"
    output += table("workspace", {"resolver": workspace["resolver"], "members": sorted(members), "default-members": seeds})
    output += table("workspace.package", workspace["package"])
    for kind, values in workspace.get("lints", {}).items():
        output += table(f"workspace.lints.{kind}", values)
    dependencies = {name: workspace["dependencies"][name] for name in sorted(inherited)}
    if "sqlx" in dependencies:
        sqlx = dict(dependencies["sqlx"])
        # PostgreSQL server builds must not inherit the app-only SQLite driver.
        sqlx["features"] = [f for f in sqlx.get("features", []) if f not in {"sqlite", "sqlite-bundled", "mysql"}]
        dependencies["sqlx"] = sqlx
    output += table("workspace.dependencies", dependencies)
    output += table("workspace.metadata.kim-server", {"binaries": [members[s]["package"]["name"] for s in seeds]})
    for profile, values in root.get("profile", {}).items():
        values = dict(values)
        if "package" in values:
            values["package"] = {k: v for k, v in values["package"].items() if k in names or k == "*"}
            if not values["package"]:
                del values["package"]
        if values:
            output += table(f"profile.{profile}", values)
    # Desktop-only patches are omitted. Pin verification rejects source/version
    # changes if a future server dependency actually needs one of those patches.
    return output


def verify_pins(lock_path: Path) -> None:
    identity = lambda p: (p["name"], p["version"], p.get("source"), p.get("checksum"))
    root_pins = {identity(p) for p in tomllib.loads((ROOT / "Cargo.lock").read_text())["package"]}
    selected = {identity(p) for p in tomllib.loads(lock_path.read_text())["package"]}
    unexpected = selected - root_pins
    if unexpected:
        raise ValueError(f"server lock selects packages absent from root Cargo.lock: {sorted(unexpected, key=str)}; refresh root pins first")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dest", type=Path)
    parser.add_argument("--refresh-lock", action="store_true", help="derive server.Cargo.lock from root pins; review its diff")
    parser.add_argument("--offline", action="store_true", help="refresh using only the local Cargo cache")
    args = parser.parse_args()
    dest = args.dest.resolve()
    if dest.exists():
        raise ValueError(f"destination already exists; choose an empty path (nothing removed): {dest}")
    if dest == ROOT or dest in ROOT.parents:
        raise ValueError("destination must not contain the repository")
    if dest.is_relative_to(ROOT) and not dest.is_relative_to(ROOT / "target"):
        raise ValueError("use a destination outside the repository or under target/")
    root = tomllib.loads((ROOT / "Cargo.toml").read_text())
    seeds = [p for p in root["workspace"]["members"] if p.startswith("services/")]
    seeds.append("tools/kim-server-migrate")
    members, inherited = local_closure(root["workspace"], seeds)
    if not args.refresh_lock:
        verify_pins(SERVER_LOCK)
    dest.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".kim-server-stage-", dir=dest.parent) as tmp:
        stage = Path(tmp) / "context"
        stage.mkdir()
        (stage / "Cargo.toml").write_text(projected_manifest(root, members, inherited, seeds))
        shutil.copy2(ROOT / "rust-toolchain.toml", stage / "rust-toolchain.toml")
        for member in members:
            shutil.copytree(ROOT / member, stage / member, ignore=shutil.ignore_patterns("target", ".git", ".DS_Store", "__pycache__"))
        for config in CONFIGS:
            target = stage / "deploy" / config
            target.parent.mkdir(exist_ok=True)
            shutil.copy2(ROOT / "deploy" / config, target)
        shutil.copy2(ROOT / "Dockerfile", stage / "Dockerfile")
        shutil.copy2(ROOT / "Cargo.lock" if args.refresh_lock else SERVER_LOCK, stage / "Cargo.lock")
        if args.refresh_lock:
            command = ["cargo", "metadata", "--format-version", "1"]
            if args.offline:
                command.append("--offline")
            result = subprocess.run(command, cwd=stage, capture_output=True, text=True, check=True)
            sys.stderr.write(result.stderr)
            verify_pins(stage / "Cargo.lock")
            shutil.copy2(stage / "Cargo.lock", SERVER_LOCK)
        stage.rename(dest)
    print(f"server workspace: {len(members)} local packages; no client/agent/Codex manifests or sources")
    print(f"server context staged at {dest}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except subprocess.CalledProcessError as error:
        print(error.stderr or str(error), file=sys.stderr)
        raise SystemExit(error.returncode)
    except (OSError, KeyError, ValueError) as error:
        print(f"server context: {error}", file=sys.stderr)
        raise SystemExit(1)
